public class Loops {
    public static void main(String[] args) {
        System.out.println("For loop:");
        for (int number = 1; number <= 5; number++) {
            System.out.println(number);
        }

        System.out.println("While loop:");
        int count = 1;
        while (count <= 5) {
            System.out.println(count);
            count++;
        }
    }
}
