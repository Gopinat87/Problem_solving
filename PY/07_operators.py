# Concept 7: Operators
a = 20
b = 6

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** 2)

print("Is a greater than b?", a > b)
print("Are both positive?", a > 0 and b > 0)
